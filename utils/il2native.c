/* il2native.c - CLR AOT Compiler Tool
 *
 * Compiles a .NET DLL into QBE Intermediate Language (IL) using the
 * kernel CLR components (il_parser, il_to_fruity, fruity_to_qbe).
 *
 * Capabilities:
 * 1. Parses .NET DLL
 * 2. Generates QBE IL for all methods with bodies
 * 3. Detects internal calls and generates assembly aliases in bindings.s
 *
 * Usage:
 *   ./il2native <input.dll> <output.ssa> <bindings.s>
 */

