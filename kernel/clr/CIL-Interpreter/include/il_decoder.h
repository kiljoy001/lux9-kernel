bool has_more_instructions(cil_decoder_t* decoder);
const char* get_opcode_name(cil_opcode_t opcode);
cil_operand_type_t get_opcode_operand_type(cil_opcode_t opcode);
bool is_extended_opcode(uint8_t opcode);

