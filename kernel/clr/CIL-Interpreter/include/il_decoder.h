// Instruction operand types
typedef enum {
    CIL_OPERAND_NONE,           // No operand
    CIL_OPERAND_BYTE,           // 1-byte operand
    CIL_OPERAND_SHORT,          // 2-byte operand
    CIL_OPERAND_INT,            // 4-byte operand
    CIL_OPERAND_LONG,           // 8-byte operand
    CIL_OPERAND_FLOAT,          // 4-byte float
    CIL_OPERAND_DOUBLE,         // 8-byte double
    CIL_OPERAND_TOKEN,          // Metadata token (4 bytes)
    CIL_OPERAND_BRANCH,         // Branch target (4 bytes)
    CIL_OPERAND_BRANCH_SHORT,   // Short branch target (1 byte)
    CIL_OPERAND_SWITCH,         // Switch table
    CIL_OPERAND_STRING,         // String token
    CIL_OPERAND_TYPE,           // Type token
    CIL_OPERAND_METHOD,         // Method token
    CIL_OPERAND_FIELD           // Field token
} cil_operand_type_t;

// CIL instruction structure
typedef struct {
    cil_opcode_t opcode;
    cil_operand_type_t operand_type;
    union {
        uint8_t byte_val;
        int16_t short_val;
        int32_t int_val;
        int64_t long_val;
        float float_val;
        double double_val;
        uint32_t token;
        int32_t branch_offset;
        uint8_t branch_offset_short;
        struct {
            uint32_t num_targets;
            int32_t* targets;
        } switch_table;
    } operand;
    size_t size;  // Total size of instruction in bytes
} cil_instruction_t;

// Decoder state
typedef struct {
    const uint8_t* bytecode;
    size_t bytecode_size;
    size_t offset;
    bool has_error;
    const char* error_message;
} cil_decoder_t;

// Function prototypes
