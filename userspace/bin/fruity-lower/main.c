/* main.c - Fruity Lowering Tool Entry Point
 *
 * Usage: fruity-lower <input.dll> [-o output.fir]
 */

#define _POSIX_C_SOURCE 200809L

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <getopt.h>
#include "msil_reader.h"
#include "fruity_lowering.h"

static void print_usage(const char *prog)
{
	fprintf(stderr, "Usage: %s <input.dll> [-o output.fir] [-v]\n", prog);
	fprintf(stderr, "\n");
	fprintf(stderr, "Options:\n");
	fprintf(stderr, "  -o FILE    Output Fruity IR file (default: stdout)\n");
	fprintf(stderr, "  -v         Verbose mode (print MSIL and Fruity IR)\n");
	fprintf(stderr, "  -h         Show this help\n");
	fprintf(stderr, "\n");
	fprintf(stderr, "Lowers MSIL bytecode to Fruity IR with explicit Pebble operations.\n");
}

int main(int argc, char *argv[])
{
	const char *input_file = NULL;
	const char *output_file = NULL;
	int verbose = 0;
	int opt;

	/* Parse command line */
	while ((opt = getopt(argc, argv, "o:vh")) != -1) {
		switch (opt) {
		case 'o':
			output_file = optarg;
			break;
		case 'v':
			verbose = 1;
			break;
		case 'h':
			print_usage(argv[0]);
			return 0;
		default:
			print_usage(argv[0]);
			return 1;
		}
	}

	if (optind >= argc) {
		fprintf(stderr, "Error: No input file specified\n\n");
		print_usage(argv[0]);
		return 1;
	}

	input_file = argv[optind];

	printf("Fruity Lowering Tool\n");
	printf("====================\n");
	printf("Input:  %s\n", input_file);
	printf("Output: %s\n", output_file ? output_file : "<stdout>");
	printf("\n");

	/* Open MSIL assembly */
	msil_assembly_t *assembly = msil_assembly_open(input_file);
	if (!assembly) {
		fprintf(stderr, "Error: Failed to open assembly: %s\n", input_file);
		return 1;
	}

	/* TODO: For now, we need a way to extract bytecode from .dll
	 * This is a placeholder - a real implementation would parse PE/COFF
	 * and extract method bodies from the MethodDef table.
	 */

	printf("WARNING: PE/COFF parsing not yet implemented\n");
	printf("To test the lowering pipeline, you need to provide raw bytecode.\n");
	printf("\n");

	/* Example: Create a simple test method with raw bytecode */
	printf("Creating test method with sample bytecode...\n");

	msil_method_t *test_method = msil_method_create("TestMethod");
	if (!test_method) {
		fprintf(stderr, "Error: Failed to create test method\n");
		msil_assembly_close(assembly);
		return 1;
	}

	test_method->token = 0x06000001;
	test_method->local_count = 2;
	test_method->arg_count = 0;
	test_method->max_stack = 8;

	/* Sample MSIL bytecode:
	 *   newobj    instance void [mscorlib]System.Object::.ctor()
	 *   stloc.0
	 *   ldloc.0
	 *   dup
	 *   stloc.1
	 *   pop
	 *   ret
	 */
	uint8_t sample_code[] = {
		0x73, 0x01, 0x00, 0x00, 0x06,  /* newobj 0x06000001 */
		0x0A,                           /* stloc.0 */
		0x06,                           /* ldloc.0 */
		0x25,                           /* dup */
		0x0B,                           /* stloc.1 */
		0x26,                           /* pop */
		0x2A                            /* ret */
	};

	if (msil_method_parse_bytecode(test_method, sample_code, sizeof(sample_code)) < 0) {
		fprintf(stderr, "Error: Failed to parse bytecode\n");
		msil_method_destroy(test_method);
		msil_assembly_close(assembly);
		return 1;
	}

	printf("\n=== MSIL Method ===\n");
	msil_method_print(test_method);

	/* Lower MSIL to Fruity IR */
	printf("\n=== Lowering to Fruity IR ===\n");
	fruity_function_t *fruity_func = lower_msil_to_fruity(test_method);
	if (!fruity_func) {
		fprintf(stderr, "Error: Failed to lower to Fruity IR\n");
		msil_method_destroy(test_method);
		msil_assembly_close(assembly);
		return 1;
	}

	printf("\n=== Fruity IR Function ===\n");
	fruity_function_print(fruity_func);

	/* Serialize to file if specified */
	if (output_file) {
		printf("\nWriting Fruity IR to: %s\n", output_file);
		FILE *out = fopen(output_file, "w");
		if (!out) {
			fprintf(stderr, "Error: Failed to open output file: %s\n", output_file);
			fruity_function_destroy(fruity_func);
			msil_method_destroy(test_method);
			msil_assembly_close(assembly);
			return 1;
		}

		/* TODO: Implement Fruity IR serialization format */
		fprintf(out, "; Fruity IR Module\n");
		fprintf(out, "; Generated by fruity-lower\n\n");

		/* For now, just print the function */
		/* A real implementation would use a proper serialization format */
		fprintf(out, ".function %s\n", fruity_func->name);
		fprintf(out, "{\n");

		fruity_basic_block_t *block = fruity_func->blocks_head;
		while (block) {
			fprintf(out, "  .block %u:\n", block->block_id);

			fruity_instruction_t *instr = block->instructions_head;
			while (instr) {
				fprintf(out, "    %s", fruity_opcode_name(instr->opcode));

				/* Print operand based on type */
				switch (instr->operand.type) {
				case FRUITY_OP_IMM_I32:
					fprintf(out, " %d", instr->operand.value.i32);
					break;
				case FRUITY_OP_IMM_I64:
					fprintf(out, " %ld", instr->operand.value.i64);
					break;
				case FRUITY_OP_IMM_R32:
					fprintf(out, " %f", instr->operand.value.r32);
					break;
				case FRUITY_OP_IMM_R64:
					fprintf(out, " %f", instr->operand.value.r64);
					break;
				case FRUITY_OP_LOCAL:
				case FRUITY_OP_ARG:
				case FRUITY_OP_FIELD:
					fprintf(out, " %u", instr->operand.value.index);
					break;
				case FRUITY_OP_TYPE:
				case FRUITY_OP_METHOD:
					fprintf(out, " 0x%08X", instr->operand.value.token);
					break;
				case FRUITY_OP_BRANCH:
					if (instr->operand.value.target)
						fprintf(out, " .block%u", instr->operand.value.target->block_id);
					break;
				case FRUITY_OP_TASKLET:
					fprintf(out, " tasklet_%u", instr->operand.value.tasklet);
					break;
				default:
					break;
				}

				fprintf(out, "\n");
				instr = instr->next;
			}

			block = block->next;
		}

		fprintf(out, "}\n");
		fclose(out);
	}

	printf("\nLowering complete!\n");

	/* Cleanup */
	fruity_function_destroy(fruity_func);
	msil_method_destroy(test_method);
	msil_assembly_close(assembly);

	return 0;
}
